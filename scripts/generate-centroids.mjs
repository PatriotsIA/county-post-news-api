// Precompute existing geometry once instead of in every cold Lambda environment.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import centroid from "@turf/centroid";
import { feature } from "topojson-client";
const require = createRequire(import.meta.url);
const topology = require("us-atlas/counties-10m.json");
const rows = feature(topology, topology.objects.counties).features.map(county => {
  const [lon, lat] = centroid(county).geometry.coordinates;
  return [String(county.id).padStart(5, "0"), [lat, lon]];
});
// Census 2025 Gazetteer internal points; the newer areas are absent from us-atlas.
// https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_counties_national.zip
// Higher-precision values: https://tigerweb.geo.census.gov/tigerwebmain/Files/acs25/tigerweb_acs25_county_ak.html
// Aleutians West straddles the dateline; averaging wrapped longitudes misplaced it.
const corrections = { "02016": [51.9489640, 179.6211882], "02063": [60.4884737, -146.2030904], "02066": [62.0344790, -143.9221674] };
const data = Object.fromEntries(rows);
Object.assign(data, corrections);
const lines = Object.entries(data).sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
writeFileSync(new URL("../src/county-centroid-data.ts", import.meta.url), `// Generated by scripts/generate-centroids.mjs. Do not edit.\nexport const countyCentroidData: Record<string, readonly [number, number]> = {\n${lines.join("\n")}\n};\n`);
console.log(`Generated ${lines.length} county points; preserved existing coordinates except the documented Alaska corrections.`);
